/**
 * @brief Encode @p tx unsigned and signed, and hold both — and the digest the
 *        card is asked to sign — against the vector.
 */
static void check(const eth_tx_t *tx,
                  const uint8_t *unsigned_exp, size_t unsigned_len,
                  const uint8_t sighash[32],
                  uint8_t v, const uint8_t r[32], const uint8_t s[32],
                  const uint8_t *signed_exp, size_t signed_len)
{
    uint8_t buf[300];

    const size_t un = eth_rlp_encode_unsigned(tx, buf, sizeof(buf));
    assert(un == unsigned_len);
    assert(memcmp(buf, unsigned_exp, un) == 0);

    uint8_t h[32];
    keccak256(buf, un, h);
    assert(memcmp(h, sighash, 32) == 0);

    const size_t sn = eth_rlp_encode_signed(tx, v, r, s, buf, sizeof(buf));
    assert(sn == signed_len);
    assert(memcmp(buf, signed_exp, sn) == 0);

    /* One byte short of either is a refusal, never a truncated transaction. */
    assert(eth_rlp_encode_unsigned(tx, buf, unsigned_len - 1U) == 0U);
    assert(eth_rlp_encode_signed(tx, v, r, s, buf, signed_len - 1U) == 0U);
    /* And exactly enough is enough. */
    assert(eth_rlp_encode_signed(tx, v, r, s, buf, signed_len) == signed_len);
}

int main(void)
{
    /* ── 12.50 USDC on Sepolia: the ERC-20 path end to end ─────────── */
    /* The calldata comes from money.h, as main.cpp builds it, so this is also
     * the transfer(address,uint256) layout inside a real signed transaction. */
    uint8_t calldata[USDC_CALLDATA_LEN];
    build_usdc_calldata(calldata, PAYEE, 12500000U);

    eth_tx_t usdc;
    memset(&usdc, 0, sizeof(usdc));
    usdc.chain_id         = 11155111U;
    usdc.nonce            = 7U;
    usdc.max_priority_fee = 20000000000ULL;
    usdc.max_fee          = 30000000000ULL;
    usdc.gas_limit        = 100000U;
    memcpy(usdc.to, USDC_SEPOLIA, 20);
    usdc.eth_value        = 0U;
    usdc.calldata         = calldata;
    usdc.calldata_len     = sizeof(calldata);
    check(&usdc, USDC_UNSIGNED, sizeof(USDC_UNSIGNED), USDC_SIGHASH,
          USDC_V, USDC_R, USDC_S, USDC_SIGNED, sizeof(USDC_SIGNED));

    /* ── The largest native sale, on Polygon, nonce 0 ─────────────── */
    /* POS_AMOUNT_UNITS_MAX_NATIVE of POL — the value is the uint64 the keypad
     * cap exists to keep from wrapping — and a zero nonce, RLP's empty string. */
    uint64_t max_wei = 0U;
    assert(evm_units_to_wei(POS_AMOUNT_UNITS_MAX_NATIVE, &max_wei));

    eth_tx_t pol;
    memset(&pol, 0, sizeof(pol));
    pol.chain_id         = 137U;
    pol.nonce            = 0U;
    pol.max_priority_fee = 30000000000ULL;
    pol.max_fee          = 30000000000ULL;
    pol.gas_limit        = 21000U;
    memcpy(pol.to, PAYEE, 20);
    pol.eth_value        = max_wei;
    pol.calldata         = NULL;
    pol.calldata_len     = 0U;
    check(&pol, POLMAX_UNSIGNED, sizeof(POLMAX_UNSIGNED), POLMAX_SIGHASH,
          POLMAX_V, POLMAX_R, POLMAX_S, POLMAX_SIGNED, sizeof(POLMAX_SIGNED));

    /* ── Mainnet ETH, a two-byte nonce and a 31-byte r ────────────── */
    /* The generator searched for the nonce: r has a leading zero byte, which the
     * encoder has to strip (0x9f, not 0xa0 0x00), and v is 0, not 1. */
    assert(ETHSHORTR_R[0] == 0x00U);
    assert(ETHSHORTR_V == 0U);

    eth_tx_t eth;
    memset(&eth, 0, sizeof(eth));
    eth.chain_id         = 1U;
    eth.nonce            = 176U;
    eth.max_priority_fee = 2000000000ULL;
    eth.max_fee          = 500000000000ULL;
    eth.gas_limit        = 21000U;
    memcpy(eth.to, PAYEE, 20);
    eth.eth_value        = 1000000000000ULL;   /* one keypad unit, 0.000001 ETH */
    eth.calldata         = NULL;
    eth.calldata_len     = 0U;
    check(&eth, ETHSHORTR_UNSIGNED, sizeof(ETHSHORTR_UNSIGNED), ETHSHORTR_SIGHASH,
          ETHSHORTR_V, ETHSHORTR_R, ETHSHORTR_S, ETHSHORTR_SIGNED,
          sizeof(ETHSHORTR_SIGNED));

    /* ── Calldata past the scratch bound is refused, not overrun ──── */
    static uint8_t big[CALLDATA_MAX + 1U];
    usdc.calldata     = big;
    usdc.calldata_len = sizeof(big);
    uint8_t out[600];
    assert(eth_rlp_encode_unsigned(&usdc, out, sizeof(out)) == 0U);
    assert(eth_rlp_encode_signed(&usdc, 0U, USDC_R, USDC_S, out, sizeof(out)) == 0U);

    printf("test_eth_rlp ... OK\n");
    return 0;
}
